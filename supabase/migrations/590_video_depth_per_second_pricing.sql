-- Video Depth Anything (decided 2026-11-03): charged per whole second of the
-- input clip, 20 base credits a second, the probed length rounded UP (a clip
-- under 1 s pays for 1 s), up to the provider's 300 s cap (a longer clip is
-- still refused before anything is reserved). One row per second,
-- `video-depth-anything:1s` … `:300s`, picked by `videoDepthCreditId`
-- (packages/shared/src/video-depth.ts) on every path: the route's guard and
-- reservation, the workflow run's stamp and reservation, every estimate. The
-- video-depth worker sets no metered cost, so the reserved row is committed
-- verbatim as the charge.
--
-- Replaces the 15/30/60/120/300 s buckets of 502, which stay in place: those
-- five rows already hold the per-second price (20 credits × their length) and
-- are listed here at the same values, so they keep whatever an administrator
-- set. The bare `video-depth-anything` row stays the 300 s ceiling (6000), and
-- Depth Anything per frame (`depth-anything-frames:*`) keeps its buckets.
--
-- WHY A SELECT AND NOT A PLAIN VALUES LIST. A reservation reads the switches
-- of the row it reserves (`is_enabled`, `tier_restriction`: readPricingRow in
-- backend/src/ee/billing/credits.ts), so a second that 502 priced from a bucket
-- row an administrator switched off or restricted to a tier must not come back
-- on through its own new row. Each row therefore takes `is_enabled`,
-- `tier_restriction` and `category` (the columns migration 419 carries for the
-- same reason) from the bucket row that priced that second before: 1–15 s from
-- `:15s`, 16–30 s from `:30s`, 31–60 s from `:60s`, 61–120 s from `:120s`,
-- 121–300 s from `:300s` — whatever this deployment holds, with nobody checking
-- first. A present bucket is copied as it is; a bucket row this deployment
-- does not have gives the defaults a row-less id prices with (enabled,
-- unrestricted) in 'video'. The ids and prices are literals: never read from a
-- bucket, so they are 20 × n whatever the buckets hold. Values MUST match
-- STATIC_CREDIT_COSTS (credit-pricing-migration-sync.test.ts,
-- static-costs-match-migrations.test.ts); the inheritance is proven by
-- supabase/tests/video-depth-per-second-pricing.behavior.sql.
--
-- ON CONFLICT DO NOTHING keeps any admin override, and makes a second run a
-- no-op.
