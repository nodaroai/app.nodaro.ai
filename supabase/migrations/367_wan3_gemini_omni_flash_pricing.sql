-- Wan 3.0 / Wan 3.0 Prime (KIE wan/3-0-video, wan/3-0-video-prime) and Gemini
-- Omni Flash (KIE google/gemini-omni-flash-1-1) pricing — serve the
-- generate-video / image-to-video / text-to-video nodes and generate-video-pro.
--
-- Wan 3.0: true per-second billing at three published resolution rates, one
-- seeded row per allowed duration (2-30s) × 480p/720p/1080p. KIE cr/s at
-- 480P/720P/1080P: wan-3 8 / 16 / 32, wan-3-prime 12.2 / 25.2 / 50.4.
-- Formula (same conversion as minimax-h3 and happyhorse):
--   Nodaro credits = ceil(KIE cr/s × duration / 4) × 10
-- ONE ROW PER SECOND rather than a coarse ladder: the tier lookup snaps UP and
-- falls back to the LAST tier, and commit_credits can only refund a surplus —
-- never collect an upward delta.
-- Prime is KIE's HIGH-SPEED tier (faster turnaround, higher per-second rate),
-- not a quality tier.
-- The bare ids are the DEFAULT render (5s @ 720p): duration falls back to the
-- global 5s and resolution to PRICING_DEFAULT_RESOLUTION (@nodaro/shared),
-- which is the 720P the provider layer pins on the wire.
-- Reference-video runs bill OUTPUT seconds only, so there is no "-ref"
-- dimension and no compute hook (unlike seedance-2 / minimax-h3).
--
-- Gemini Omni Flash: sibling of gemini-omni-video — same request shape and the
-- same 4/6/8/10s ladder, cheaper at every tier. Priced by (resolution band ×
-- duration), flat per generation when a source video is supplied (":vref").
-- Lowercase "4k". Nodaro credits = ceil(KIE cr × 2.5 / 10) × 10.
--
-- Values MUST match STATIC_CREDIT_COSTS in backend/src/ee/billing/credits.ts.
-- Per CLAUDE.md Provider Enum Sync step 9: ON CONFLICT DO NOTHING (preserves
-- admin overrides).

