/**
 * The public per-model LLM rate table, `docs/pricing/llm-models.md`.
 *
 *   npx tsx scripts/gen-llm-rate-table.ts           write the page
 *   npx tsx scripts/gen-llm-rate-table.ts --check   exit 1 when the page is stale
 *
 * Every LLM node and helper is charged for the tokens its call actually used,
 * at the rate of the model that ran it on the lane that served it. This page
 * states those rates as CHARGED credits per million tokens — the per-model
 * provider rates (`lib/pricing/llm-cost.ts`) through `usdToCredits` and the
 * platform's markup rounding at the hosted deployment's global setting
 * (`docs-price-settings.json`) — never a provider price and never a
 * percentage. Each figure carries its `credits-llm-rate:` annotation, so the
 * docs test (`docs-charged-prices.test.ts`) and `npm run docs:prices` hold
 * it to the same rule, and the docs test fails a page that differs from this
 * generator's output.
 *
 * A model is listed when a picker offers it (`PICKABLE_LLM_MODELS`), with
 * every lane it may be served — and so charged — on, its default lane first
 * (`llmPossibleLanes`). A model missing a rate on any of those lanes cannot be
 * run (`llm_model_unpriced`) and is listed as such.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { realpathSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { PICKABLE_LLM_MODELS, type LlmModelDef } from "@nodaro/shared/llm-models"
import { llmPossibleLanes, llmRateCard } from "../src/lib/pricing/llm-cost.js"
import { REPO_ROOT, llmFigurePricing, loadDocsPriceSettings, type DocsLlmFigure, type DocsLlmLane, type LlmFigureOf } from "./lib/docs-prices.js"

export const LLM_RATE_TABLE_PAGE = "docs/pricing/llm-models.md"

const LANE_NAME: Record<DocsLlmLane, string> = {
  kie: "Aggregator",
  direct: "Provider's own API",
}

function figure(llmOf: LlmFigureOf, f: Extract<DocsLlmFigure, { kind: "per-million" }>): string {
  const credits = llmOf(f)
  if (credits === undefined) throw new Error(`no ${f.lane} rate for ${f.modelId}`)
  const id = `${f.modelId}:${f.lane}:${f.direction}${f.band === "long" ? ":long" : ""}`
  return `${credits.toLocaleString("en-US")}<!-- credits-llm-rate: ${id} -->`
}

function rows(model: LlmModelDef, llmOf: LlmFigureOf): string[] {
  const lanes = llmPossibleLanes(model)
  const missing = lanes.filter((lane) => !llmRateCard(model.id, lane))
  if (missing.length > 0) {
    return [`| ${model.displayName} | \`${model.id}\` | — | not available: no price yet | — |`]
  }
  return lanes.flatMap((lane, i) => {
    const card = llmRateCard(model.id, lane)!
    const laneCell = `${LANE_NAME[lane]}${i === 0 ? " (default)" : ""}`
    const at = (direction: "input" | "output", band: "base" | "long") =>
      figure(llmOf, { kind: "per-million", modelId: model.id, lane, direction, band })
    const out = [`| ${model.displayName} | \`${model.id}\` | ${laneCell} | ${at("input", "base")} | ${at("output", "base")} |`]
    if (card.longContext) {
      const over = card.longContext.thresholdTokens.toLocaleString("en-US")
      out.push(`| ${model.displayName} | \`${model.id}\` | ${LANE_NAME[lane]}, prompt over ${over} tokens | ${at("input", "long")} | ${at("output", "long")} |`)
    }
    return out
  })
}

/** The page, at the settings in `docs-price-settings.json`. */
export function renderLlmRateTable(settings = loadDocsPriceSettings()): string {
  const llmOf = llmFigurePricing(settings)
  return [
    "<!-- Generated by backend/scripts/gen-llm-rate-table.ts from the per-model rates. Do not edit by hand: run `cd backend && npx tsx scripts/gen-llm-rate-table.ts`. -->",
    "# LLM model rates",
    "",
    "Every LLM node and helper — Generate Text, AI Writer, Prompt Helper, Generate Structured, Describe to Picker, Text to Picker, Generate Script, the motion-graphics and 3D authoring nodes, Image to Text, QA Check, Image Critic, Choose Best's AI judge, the scrapes' ad analysis and the description and caption helpers — is charged for the tokens its call actually used, at the rate of the model that ran it, on the lane that served it.",
    "",
    "- **Before the call** a small hold is reserved: the call's first attempt at the model's output cap. A run your balance cannot cover is refused before it starts (`402`, \"Needs up to N credits\"). An image approval is never refused for credits: its caption is skipped instead, and can be written later. The scrapes' ad analysis holds differently: a typical analysis per requested ad or post, not the output cap.",
    "- **After the call** the run is charged what it used — less than the hold, or more (a retry, a long answer). Anything above the hold is taken from your balance; whatever the balance cannot cover is written off, never billed later.",
    "- **The figure before a run** (`≈N` on the Run button, in the model pickers and from `POST /v1/credits/model-costs`) is an estimate: a typical call of that node on that model.",
    "- **A call's charge** is its input and output tokens at the rates below, added up and rounded up to a whole credit once, with a minimum of 2<!-- credits-llm-rate: gemini-3-flash:kie@1/1 --> credits for any call the provider served. Because each figure below is itself rounded up, multiplying tokens by them can read a credit above the real charge.",
    "- **Lanes.** A model runs on its default lane. On some models a call is served on another lane — the provider's own API for Advanced mode, for a Claude model given any reasoning effort, or when the default lane fails — and is charged at that lane's rate.",
    "- **Failures.** A failed call the provider still billed (a refusal, a cut-off answer, an answer that could not be used) is charged for that usage, and the error says so. A failure the provider did not bill is refunded. A stream you stop is charged for the prompt and the text produced before you stopped it.",
    "",
    "Workflow Copilot is priced separately and is not charged by these rates.",
    "",
    "## Credits per million tokens",
    "",
    "| Model | Id | Lane | Input | Output |",
    "|---|---|---|---|---|",
    ...PICKABLE_LLM_MODELS.flatMap((m) => rows(m, llmOf)),
    "",
    "See [Choosing models](../choosing-models.md#text-llm-models) for worked examples and which model each node uses by default.",
    "",
  ].join("\n")
}

function isEntryPoint(): boolean {
  if (!process.argv[1]) return false
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
  } catch {
    return false
  }
}

if (isEntryPoint()) {
  const path = join(REPO_ROOT, LLM_RATE_TABLE_PAGE)
  const next = renderLlmRateTable()
  if (process.argv.includes("--check")) {
    let current = ""
    try {
      current = readFileSync(path, "utf8")
    } catch {
      // missing counts as stale
    }
    if (current !== next) {
      console.error(`[gen-llm-rate-table] ${LLM_RATE_TABLE_PAGE} is stale — run: cd backend && npx tsx scripts/gen-llm-rate-table.ts`)
      process.exitCode = 1
    } else {
      console.log(`[gen-llm-rate-table] ${LLM_RATE_TABLE_PAGE} is current`)
    }
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, next)
    console.log(`[gen-llm-rate-table] wrote ${LLM_RATE_TABLE_PAGE}`)
  }
}
