/**
 * Render the per-type node data field table: for every NODE_DEFINITIONS entry, the fields its data
 * type declares (its `*Data` interface or type alias, fields it inherits included) together with the
 * keys of its `defaultData`. `@nodaro/render-rules` reads it to tell a node's configuration from what
 * it holds (`nodeSettingKeys`): publishing a node whose value can reach a UGC Creator's photo, or
 * made from a UGC video, keeps only its configuration.
 *
 * `declared` is false when no data type was found for the node type: its fields are then its
 * default data's keys alone, and the guard test names it.
 *
 * Output is sorted and carries no timestamp, so a run that changes nothing writes nothing.
 */
import type { InterfaceShape, NodeDef } from "./parse-node-definitions.js"

export function renderNodeDataFieldsModule(defs: ReadonlyArray<NodeDef>, shapes: ReadonlyMap<string, InterfaceShape | undefined>): string {
  const sorted = [...defs].sort((a, b) => a.type.localeCompare(b.type))
  const rows = sorted.map((d) => {
    const shape = shapes.get(d.type)
    const declared = !!shape && shape.fields.length > 0
    const fields = [...new Set([...(shape?.fields.map((f) => f.name) ?? []), ...(d.defaultDataKeys ?? Object.keys(d.defaultData ?? {}))])]
      .filter((name) => /^[A-Za-z_$][\w$]*$/.test(name))
      .sort()
    return `  ${JSON.stringify(d.type)}: { declared: ${declared}, fields: [${fields.map((f) => JSON.stringify(f)).join(", ")}] },`
  })
  return [
    "// GENERATED by `npm run gen:skills` (backend/scripts/gen-skills.ts) from",
    "// frontend/src/types/nodes.ts NODE_DEFINITIONS and each type's *Data declaration — do NOT hand-edit.",
    "// `gen:skills:check` fails CI on drift.",
    "",
    "export interface NodeDataFieldSpec {",
    "  /** Whether the node type's data type was found (else `fields` are its default data's keys alone). */",
    "  readonly declared: boolean",
    "  /** The fields its data type declares, inherited ones included, and the keys of its default data. */",
    "  readonly fields: ReadonlyArray<string>",
    "}",
    "",
    "export const NODE_DATA_FIELDS: Readonly<Record<string, NodeDataFieldSpec>> = {",
    ...rows,
    "}",
    "",
  ].join("\n")
}
