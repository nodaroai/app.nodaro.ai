// @registry-enumerates renders one row per use-case type from its body (usecaseBodyTakesNull, usecaseBodyTakesEmpty)
/**
 * Render the per-type tables of the use-case settings a request body takes as
 * null (a None that is not the setting's default) and as an empty string
 * (free text): for every use-case type, the descriptor's setting keys whose
 * body field accepts that value (`usecaseBodyTakesNull` / `usecaseBodyTakesEmpty`,
 * read from the type's Zod body). The editor cannot import the bodies, so
 * `@nodaro/render-rules` reads these tables (`usecaseSentSettings`) and the
 * canvas's run sends what the server's engine sends.
 *
 * Output is in the descriptors' order and carries no timestamp, so a run that
 * changes nothing writes nothing.
 */
import { USE_CASE_NODE_TYPES, usecaseDescriptor } from "@nodaro/render-rules"
import { usecaseBodyTakesEmpty, usecaseBodyTakesNull } from "../../../src/lib/use-case/bodies.js"

function table(name: string, doc: string, takes: (type: (typeof USE_CASE_NODE_TYPES)[number], key: string) => boolean): string[] {
  return [
    `/** ${doc} */`,
    `export const ${name}: Readonly<Record<string, ReadonlyArray<string>>> = {`,
    ...USE_CASE_NODE_TYPES.map((type) => {
      const keys = usecaseDescriptor(type).settingKeys.filter((k) => takes(type, k))
      return `  ${JSON.stringify(type)}: [${keys.map((k) => JSON.stringify(k)).join(", ")}],`
    }),
    "}",
  ]
}

export function renderUseCaseSentSettingsModule(): string {
  return [
    "// GENERATED by `npm run gen:skills` (backend/scripts/gen-skills.ts) from each use-case",
    "// node's request body (USE_CASE_BODIES, its unit's use-case.ts) — do NOT hand-edit.",
    "// `gen:skills:check` fails CI on drift.",
    "",
    ...table("USE_CASE_NULL_SETTINGS", "Per use-case type, the settings its request body takes as null (a None that is not the default).", usecaseBodyTakesNull),
    "",
    ...table("USE_CASE_EMPTY_SETTINGS", "Per use-case type, the settings its request body takes as an empty string (free text).", usecaseBodyTakesEmpty),
    "",
  ].join("\n")
}
