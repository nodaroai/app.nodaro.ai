/**
 * Speaker View's followed cameras on an edit the plugin SPLITS at the
 * transcript's turns (P3.9; round 5, decided 2026-10-11, option (b) "assume
 * followed").
 *
 * The plugin lays the edit out AFTER splitting its unnamed segments at the
 * transcript's turns; the app's shared layout stage judges the edit as given
 * (the split is the plugin's taste and is not copied into the public app). For
 * the face tracks that matters in two places, both only where a split happens
 * (some segment names no speaker, and the transcript has a speaker label):
 *  - a fixed multi-slot layout: who sits on which camera is tallied over the
 *    NAMED segments, and the split names every piece, so a speaker can land on
 *    a camera the edit as given never put them on;
 *  - a crosstalk hint on an unnamed segment that straddles the moment a camera
 *    begins: the app snaps the whole segment, the pieces after it keep the slot.
 *
 * So for those edits the app treats every camera a non-pinned slot could follow
 * as followed: it never passes a render the plugin refuses, and may refuse one
 * the plugin would pass. The plugin's own splits are in
 * `speaker-view-turn-split.json` (generated by `splitSpeakerTurns`, plugin
 * main 39ada9ea): the fixture holds no refusals, so "the plugin refuses" is
 * derived by laying out its split exactly as the plugin does (the split edit,
 * the slot set of the edit as given).
 */
import { readFileSync } from "node:fs"
import { describe, expect, it } from "vitest"
import {
  findSpeakerViewIssues,
  layOutSpeakerView,
  findSpeakerViewTrackIssues,
  speakerViewFollowedCameras,
  speakerViewFollowedTrackCameras,
  speakerViewSlotSet,
} from "@nodaro/render-rules"
import { transcriptSpeakerLabels, type Edl, type SpeakerTrackSetDescriptor } from "@nodaro/shared"

type Turn = [string | null, number, number]
interface FixtureCase {
  readonly name: string
  readonly edl: Edl
  readonly turns: Turn[] | null
  readonly transcriptAsString: boolean
  readonly split: Edl | "unchanged"
}
const FIXTURE = JSON.parse(readFileSync(new URL("../../providers/video/__tests__/fixtures/speaker-view-turn-split.json", import.meta.url), "utf8")) as { cases: FixtureCase[] }
const caseNamed = (start: string): FixtureCase => FIXTURE.cases.find((c) => c.name.startsWith(start))!

/** The fixture's words: one every 500 ms across each turn, 450 ms long. */
function talk(turns: readonly Turn[]) {
  const words: Array<{ text: string; startMs: number; endMs: number; speaker?: string }> = []
  for (const [speaker, a, b] of turns) {
    for (let t = a; t < b; t += 500) words.push({ text: "w", startMs: t, endMs: Math.min(t + 450, b), ...(speaker ? { speaker } : {}) })
  }
  return { version: 1, words }
}
const transcriptOf = (c: FixtureCase): unknown => (c.turns === null ? undefined : c.transcriptAsString ? JSON.stringify(talk(c.turns)) : talk(c.turns))

const SHA = "b".repeat(64)
const FAR = { startMs: 10_000_000, endMs: 10_001_000 }

/** Face tracks with a row per video source of `edl`; `spans` overrides what a camera's row sampled. */
function tracksFor(edl: Edl, spans: Record<string, Array<{ startMs: number; endMs: number }>> = {}): SpeakerTrackSetDescriptor {
  return {
    version: 1,
    sampleFps: 2,
    detector: { id: "yunet" },
    url: "https://media.example/users/u1/speaker-tracks/11111111-2222-3333-4444-555555555555.json",
    sha256: SHA,
    bytes: 1_000,
    sources: edl.sources
      .filter((s) => s.kind === "video")
      .map((s) => ({
        sourceId: s.id,
        clock: "source" as const,
        frame: { w: 1920, h: 1080 },
        sampledSpans: spans[s.id] ?? [{ startMs: 0, endMs: 1_000_000 }],
        tracks: [{ id: `${s.id}/t1`, boxCount: 10 }],
      })),
  }
}

/** The cameras the PLUGIN follows: its split edit, laid out with the slot set
 *  of the edit as given (`input.ts` of the plugin). */
function pluginFollowed(c: FixtureCase, layout: string): Set<string> | undefined {
  const transcript = transcriptOf(c)
  const labels = transcript === undefined ? [] : transcriptSpeakerLabels(transcript)
  const split = c.split === "unchanged" ? c.edl : c.split
  const laid = layOutSpeakerView(split, { layout, aspect: "16:9", speakers: speakerViewSlotSet(c.edl, labels) })
  if (laid.unplaced.length > 0) return undefined
  return speakerViewFollowedCameras(laid.drawn, tracksFor(c.edl), undefined)
}

/** The cameras the app follows on the edit as given, with no split in mind. */
function asGivenFollowed(edl: Edl, layout: string, transcript?: unknown): Set<string> {
  const labels = transcript === undefined ? [] : transcriptSpeakerLabels(transcript)
  const laid = layOutSpeakerView(edl, { layout, aspect: "16:9", speakers: speakerViewSlotSet(edl, labels) })
  return speakerViewFollowedCameras(laid.drawn, tracksFor(edl), undefined)
}

const LAYOUTS = ["auto", "single", "side-by-side", "stacked", "grid", "pip"]

describe("the badge's followed cameras contain the plugin's, on every split in the plugin's fixture", () => {
  let compared = 0
  for (const c of FIXTURE.cases) {
    for (const layout of LAYOUTS) {
      it(`${layout}: ${c.name}`, () => {
        const plugin = pluginFollowed(c, layout)
        if (plugin === undefined) return // a speaker no camera places: refused before any track is read
        const badge = speakerViewFollowedTrackCameras({ edl: c.edl, transcript: transcriptOf(c), settings: { layout, tracks: tracksFor(c.edl) } })
        if (badge === undefined) return // the app's layout places no one: its own refusal comes first
        compared++
        for (const camera of plugin) expect(badge, `plugin follows ${camera}`).toContain(camera)
      })
    }
  }

  it("compares a real number of cases (the loop above is not skipping them all)", () => {
    expect(compared).toBeGreaterThanOrEqual(FIXTURE.cases.length * 2)
  })
})

describe("an unnamed edit the plugin splits: the badge refuses what the plugin refuses", () => {
  const c = caseNamed("three cameras")
  const edl = c.edl
  const transcript = transcriptOf(c)
  const settings = (tracks: SpeakerTrackSetDescriptor) => ({ layout: "side-by-side", tracks })
  // camC is the camera the unnamed middle is on; its tracks sampled nothing the render reads.
  const uncoveredC = tracksFor(edl, { camC: [FAR] })

  it("the plugin's split puts both speakers on camC, which the edit as given never does", () => {
    expect([...pluginFollowed(c, "side-by-side")!]).toEqual(["camC"])
    expect(asGivenFollowed(edl, "side-by-side", transcript).has("camC")).toBe(false)
  })

  it("the plugin's own layout of its split refuses camC's missing coverage", () => {
    const labels = transcriptSpeakerLabels(transcript)
    const laid = layOutSpeakerView(c.split as Edl, { layout: "side-by-side", aspect: "16:9", speakers: speakerViewSlotSet(edl, labels) })
    const verdict = findSpeakerViewTrackIssues({ edl: c.split as Edl, drawn: laid.drawn, tracks: uncoveredC })
    expect(verdict.issues.map((i) => i.message)).toEqual([`Face tracks don't cover "camC" — re-run Speaker Frames on this edit.`])
  })

  it("so the badge refuses it too, in the plugin's words", () => {
    const verdict = findSpeakerViewIssues({ edl, transcript, settings: settings(uncoveredC) })
    expect(verdict.ok).toBe(false)
    expect(verdict.issues.map((i) => i.message)).toEqual([`Face tracks don't cover "camC" — re-run Speaker Frames on this edit.`])
  })

  it("checks camC's file and offset too (the self-host route's scope and the badge's)", () => {
    const tracks = tracksFor(edl)
    const sampled = { sources: edl.sources.filter((s) => s.kind === "video").map((s) => ({ id: s.id, url: s.id === "camC" ? "https://f.test/other.mp4" : s.url, offsetMs: 0 })) }
    const verdict = findSpeakerViewIssues({ edl, transcript, settings: settings(tracks), tracksProvenance: sampled })
    expect(verdict.issues.map((i) => i.message)).toEqual([`Face tracks for "camC" were made from a different file — re-run Speaker Frames on this edit.`])
    expect([...speakerViewFollowedTrackCameras({ edl, transcript, settings: settings(tracks) })!].sort()).toEqual(["camA", "camB", "camC"])
  })

  it("passes when every camera it might follow is covered", () => {
    expect(findSpeakerViewIssues({ edl, transcript, settings: settings(tracksFor(edl)) }).ok).toBe(true)
  })

  it("is unchanged under Auto and Single, where the pieces keep their segment's camera", () => {
    for (const layout of ["auto", "single"]) {
      expect([...speakerViewFollowedTrackCameras({ edl, transcript, settings: { layout, tracks: uncoveredC } })!].sort()).toEqual([...asGivenFollowed(edl, layout, transcript)].sort())
    }
    // camC is the unnamed segment's own camera: followed (and refused) under Auto either way.
    expect(findSpeakerViewIssues({ edl, transcript, settings: { layout: "auto", tracks: uncoveredC } }).issues.map((i) => i.message)).toEqual([
      `Face tracks don't cover "camC" — re-run Speaker Frames on this edit.`,
    ])
  })
})

describe("a labelled edit is unchanged", () => {
  const c = caseNamed("three cameras")
  const named: Edl = { ...c.edl, segments: c.edl.segments.map((s) => (s.speaker ? s : { ...s, speaker: "Host" })) }
  const transcript = transcriptOf(c)
  const unmatched = tracksFor(named, { camC: [FAR] })

  it("names exactly the cameras the layout shows, with a transcript wired or not", () => {
    for (const layout of LAYOUTS) {
      const exact = [...asGivenFollowed(named, layout, transcript)].sort()
      expect([...speakerViewFollowedTrackCameras({ edl: named, transcript, settings: { layout, tracks: unmatched } })!].sort(), layout).toEqual(exact)
      expect([...speakerViewFollowedTrackCameras({ edl: named, settings: { layout, tracks: unmatched } })!].sort(), layout).toEqual([...asGivenFollowed(named, layout)].sort())
    }
  })

  it("refuses a camera its layout follows with no coverage, exactly as before", () => {
    // Auto: the named middle segment shows camC, so camC is followed and uncovered.
    const verdict = findSpeakerViewIssues({ edl: named, transcript, settings: { layout: "auto", tracks: unmatched } })
    expect(verdict.issues.map((i) => i.message)).toEqual([`Face tracks don't cover "camC" — re-run Speaker Frames on this edit.`])
    expect(findSpeakerViewIssues({ edl: named, transcript, settings: { layout: "auto", tracks: tracksFor(named) } }).ok).toBe(true)
  })

  it("an unnamed edit with no transcript, or a transcript with no speaker label, is not split", () => {
    const labelless = { version: 1, words: [{ text: "w", startMs: 0, endMs: 450 }] }
    for (const t of [undefined, labelless]) {
      const rule = (edl: Edl) => speakerViewFollowedTrackCameras({ edl, ...(t ? { transcript: t } : {}), settings: { layout: "side-by-side", tracks: tracksFor(edl) } })
      // The unnamed middle segment stays unnamed in both: the set is the as-given layout's.
      const got = rule(c.edl)
      expect(got === undefined ? undefined : [...got].sort()).toEqual(
        (() => {
          const laid = layOutSpeakerView(c.edl, { layout: "side-by-side", aspect: "16:9", speakers: speakerViewSlotSet(c.edl, []) })
          return laid.unplaced.length > 0 ? undefined : [...speakerViewFollowedCameras(laid.drawn, tracksFor(c.edl), undefined)].sort()
        })(),
      )
    }
  })
})

describe("a crosstalk hint on an unnamed segment that straddles a camera beginning (the snap)", () => {
  const c = caseNamed("a crosstalk hint")
  const edl = c.edl
  const transcript = transcriptOf(c)

  it("the plugin's pieces after camB begins keep its slot; the edit as given snaps it away", () => {
    expect(pluginFollowed(c, "auto")!.has("camB")).toBe(true)
    expect(asGivenFollowed(edl, "auto", transcript).has("camB")).toBe(false)
  })

  it("the badge counts camB as followed, and refuses when its tracks sampled none of what the pieces read", () => {
    expect(speakerViewFollowedTrackCameras({ edl, transcript, settings: { layout: "auto", tracks: tracksFor(edl) } })!.has("camB")).toBe(true)
    const verdict = findSpeakerViewIssues({ edl, transcript, settings: { layout: "auto", tracks: tracksFor(edl, { camB: [FAR] }) } })
    expect(verdict.issues.map((i) => i.message)).toEqual([`Face tracks don't cover "camB" — re-run Speaker Frames on this edit.`])
  })

  it("reads only after the camera has begun: a hint that ends before it adds nothing", () => {
    const early: Edl = { ...edl, sources: edl.sources.map((s) => (s.id === "camB" ? { ...s, offsetMs: 90_000 } : s)) }
    expect(speakerViewFollowedTrackCameras({ edl: early, transcript, settings: { layout: "auto", tracks: tracksFor(early) } })!.has("camB")).toBe(false)
  })

  it("a hint slot with its own crop is pinned, so it adds nothing", () => {
    const pinned: Edl = {
      ...edl,
      segments: edl.segments.map((s) =>
        s.id === "c" && s.layout?.slots
          ? { ...s, layout: { ...s.layout, slots: s.layout.slots.map((sl) => (sl.source === "camB" ? { ...sl, region: { x: 0, y: 0, w: 0.5, h: 1 } } : sl)) } }
          : s,
      ),
    }
    expect(speakerViewFollowedTrackCameras({ edl: pinned, transcript, settings: { layout: "auto", tracks: tracksFor(pinned) } })!.has("camB")).toBe(false)
  })
})
