/**
 * The fixture's face turned `yawDeg` about its vertical axis (positive: its nose toward the image's right) and seen
 * straight on (orthographic), `height` pixels from forehead to chin, centred at (`cx`, `cy`): its 2D points
 * `[x0, y0, …]` and their depths (pixels, smaller = nearer), as the pipeline carries them.
 */
export function turnedFace(yawDeg: number, o: { height?: number; cx?: number; cy?: number } = {}): { points: Float64Array; depth: Float64Array } {
  const k = (o.height ?? 100) / 100
  const cx = o.cx ?? 640
  const cy = o.cy ?? 360
  const a = (yawDeg * Math.PI) / 180
  const c = Math.cos(a)
  const s = Math.sin(a)
  const n = FRONTAL_FACE_3D.length / 3
  const points = new Float64Array(2 * n)
  const depth = new Float64Array(n)
  for (let i = 0; i < n; i++) {
    const x = FRONTAL_FACE_3D[3 * i]!, y = FRONTAL_FACE_3D[3 * i + 1]!, z = FRONTAL_FACE_3D[3 * i + 2]!
    // Turned so the nose (nearest, z < 0) moves toward +x for a positive yaw.
    points[2 * i] = cx + k * (c * x - s * z)
    points[2 * i + 1] = cy + k * y
    depth[i] = k * (s * x + c * z)
  }
  return { points, depth }
}
