const unpack = (hex: string): Uint8Array => Uint8Array.from({ length: hex.length / 2 }, (_, i) => parseInt(hex.slice(2 * i, 2 * i + 2), 16))

const TABLES: Record<VideoDepthColormap, Uint8Array> = {
  grayscale: Uint8Array.from({ length: 768 }, (_, i) => Math.floor(i / 3)),
  turbo: unpack(HEX.turbo),
  inferno: unpack(HEX.inferno),
  magma: unpack(HEX.magma),
  viridis: unpack(HEX.viridis),
}

/** `colormap`'s table: 256 packed RGB entries (768 bytes), entry `g` the colour of gray depth `g`. */
export function depthColormapTable(colormap: VideoDepthColormap): Uint8Array {
  return TABLES[colormap]
}
