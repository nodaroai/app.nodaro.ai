/** Seam id → live, over every kind of seam. `overrides` (tests) turns seams on or off. */
export function liveSeams(overrides = {}) {
  const all = [...AGGREGATES, ...SPLICES, ...DATA_FILES, ...EXECUTION_SEAMS]
  return new Set(all.filter((s) => overrides[s.id] ?? s.live).map((s) => s.id))
}

/** Every seam id, for tests that want all of them live. */
export const ALL_SEAM_IDS = [...AGGREGATES, ...SPLICES, ...DATA_FILES, ...EXECUTION_SEAMS].map((s) => s.id)
