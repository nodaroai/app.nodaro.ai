// tools/units/seams.mjs
// Every place a unit reaches the rest of the product: one generated output
// (an aggregate, a spliced region, or a data file) per concern, and the one
// central file that composes it (the "composer").
//
// A seam is LIVE once its composition point exists in the product — the
// aggregate is imported by its composer, the splice region is in the file.
// Until then gen:units emits nothing for it, and a unit that needs it fails
// validation: a node that needs a missing seam builds that seam in its own PR
// (decided 2026-10-16 — there is no exceptions list). Flipping `live` is the
// PR that adds the composer edit; the fixture test turns every seam on in a
// temporary tree, so each emitter is proven before any seam goes live.
//
// Every seam is live since PR1b: each composer composes its aggregate, and
// the splice regions exist.

