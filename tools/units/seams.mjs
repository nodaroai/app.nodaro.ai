/** Seam id → live, over the three kinds. `overrides` (tests) turns seams on or off. */
export function liveSeams(overrides = {}) {
  const all = [...AGGREGATES, ...SPLICES, ...DATA_FILES]
  return new Set(all.filter((s) => overrides[s.id] ?? s.live).map((s) => s.id))
}

