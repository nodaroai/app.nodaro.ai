// Pure rendering of the Create Image tile ledger (tools/preset-tiles/ledger.json)
// into the factory-preset modules under packages/prompts/src/factory-presets/tiles/.
// build.mts writes what this returns; preset-tiles-generated.test.ts holds the
// committed files to it, so the ledger stays the single source of every tile.

export interface LedgerTemplate {
  readonly id: string
  readonly name: string
  /** The user-facing tab (the preset's `group`). */
  readonly group: string
  /** The sub-heading inside the tab (a YouTube topic, "Instagram feed", …). */
  readonly section?: string | null
  readonly platforms?: readonly string[]
  readonly aspectRatio: string
  /** The model the tile renders with when it is not the ledger's. */
  readonly model?: string
  /** The prompt that rendered the tile's picture. Its quoted on-image phrases become the slots (see `slots`). */
  readonly prompt: string
  /**
   * The prompt already carries its `{TEXT}` placeholder (a use case written as a
   * template): this is the default the slot takes, and no quoted phrase opens.
   */
  readonly textDefault?: string
  /** How many of the person's own photos the tile works from (an edit of their picture). */
  readonly minReferences?: number
  readonly negativePrompt?: string
  /**
   * The quoted phrases of the prompt that become slots, in order: the first is
   * `{TEXT || …}`, the next `{TEXT2 || …}`, and so on. Required on a prompt that
   * quotes more than one phrase (a label or a button stays fixed, a headline
   * opens); a prompt with one quoted phrase opens that one. Each must appear in
   * the prompt exactly once.
   */
  readonly slots?: readonly string[]
  /** What the slots show, joined — the headline the tile carries. */
  readonly sampleText?: string
  /** The headline is a figure: the model may not invent a number of its own. */
  readonly figureHeadline?: boolean
  /** Who reaches for it and why — the preset's description. */
  readonly who?: string
  readonly render?: { readonly jobId: string; readonly url: string }
  /** The name and description in each interface language (the app's preset copy, keyed by preset id). */
  readonly copy?: Readonly<Partial<Record<CopyLocale, { readonly name: string; readonly description?: string }>>>
}

/** The interface languages besides English, as the app's `preset-content.<locale>.ts` files name them. */
export const COPY_LOCALES = ["he", "ja", "ko", "pt-BR"] as const
export type CopyLocale = (typeof COPY_LOCALES)[number]

/** Where the generated preset copy of one language goes (relative to the repo root). */
export const copyModulePath = (locale: CopyLocale): string => `frontend/src/lib/i18n/preset-content-tiles.${locale.toLowerCase()}.generated.ts`
const copyConst = (locale: CopyLocale) => `PRESET_TILES_${locale.toUpperCase().replace(/-/g, "_")}`

/** The tiles' preset copy for one language, in the shape of `preset-content.<locale>.ts`. */
function renderCopyModule(ledger: TileLedger, locale: CopyLocale): string {
  const rows = ledger.templates.flatMap((t) => {
    const entry = t.copy?.[locale]
    if (!entry) return []
    const value: Record<string, string> = { name: entry.name }
    if (entry.description) value.description = entry.description
    return [`  "generate-image/${t.id}": ${literal(value, "  ")},`]
  })
  return `// GENERATED by tools/preset-tiles/build.mts from tools/preset-tiles/ledger.json — do not edit.
// The Create Image tiles' names and descriptions in this language, keyed by preset id, merged into the app's preset copy (labels.ts).
import type { PresetCopy } from "./preset-content.he"

export const ${copyConst(locale)}: Record<string, PresetCopy> = {
${rows.join("\n")}
}
`
}

export interface LedgerPicker {
  readonly id: string
  readonly catalog: string
  readonly optionId: string
  readonly category?: string
  readonly label: string
  readonly aspectRatio: string
  readonly prompt: string
  readonly negativePrompt?: string
  readonly render?: { readonly jobId: string; readonly url: string }
}

export interface TileLedger {
  readonly model: string
  readonly resolution: string
  readonly templates: readonly LedgerTemplate[]
  /** The picker renders (directors, photographers, genres, aesthetics): read by the picker-renders follow-up, not by this build. */
  readonly pickers: readonly LedgerPicker[]
}

/** The folder of the generated preset modules (relative to the repo root). */
export const TILES_DIR_PATH = "packages/prompts/src/factory-presets/tiles"

/** The ledger files, in the order their tabs appear (relative to the repo root). */
export const LEDGER_PATHS = ["tools/preset-tiles/ledger.json", "tools/preset-tiles/use-cases.json"] as const

/** Several ledgers as one: the first one's model and resolution, every template in file order. A row of a later ledger carries its own `model`. */
export function mergeLedgers(ledgers: readonly TileLedger[]): TileLedger {
  const [first] = ledgers
  const seen = new Set<string>()
  for (const t of ledgers.flatMap((l) => l.templates)) {
    if (seen.has(t.id)) throw new Error(`template ${t.id} appears in more than one ledger`)
    seen.add(t.id)
  }
  return {
    model: first.model,
    resolution: first.resolution,
    templates: ledgers.flatMap((l) => l.templates.map((t) => (l === first || t.model ? t : { ...t, model: l.model }))),
    pickers: ledgers.flatMap((l) => l.pickers),
  }
}

/** The on-image text slot every text-carrying template exposes; its default is the sample the tile shows. */
export const TEXT_SLOT = "TEXT"
/** The label of the n-th slot (1-based): TEXT, TEXT2, TEXT3… */
export const slotLabel = (n: number): string => (n === 1 ? TEXT_SLOT : `${TEXT_SLOT}${n}`)

/** Appended where the ledger flags `figureHeadline`. */
const FIGURE_NOTE = "Use only the figure given in the headline; never invent numbers presented as real results."

const QUOTED_ALL = /[“"]([^”"]+)[”"]/g

/** The quoted phrases of a prompt, in order. */
export const quotedPhrases = (prompt: string): string[] => [...prompt.matchAll(QUOTED_ALL)].map((m) => m[1])

/** The phrases a template opens as slots: its `slots`, or its single quoted phrase; a `{TEXT}` template opens its default. */
export function slotPhrases(t: LedgerTemplate): readonly string[] {
  if (t.textDefault !== undefined) return [t.textDefault]
  const phrases = quotedPhrases(t.prompt)
  if (t.slots) {
    for (const phrase of t.slots) {
      const hits = phrases.filter((p) => p === phrase).length
      if (hits !== 1) throw new Error(`${t.id}: slot "${phrase}" appears ${hits} times in the prompt, not once`)
    }
    return t.slots
  }
  if (phrases.length > 1) throw new Error(`${t.id}: quotes ${phrases.length} phrases but names no slots`)
  return phrases
}
/**
 * The opening clause of a tile prompt names its ratio ("YouTube thumbnail, 16:9, …",
 * "Pinterest pin, 2:3 tall, …"). The preset's `aspectRatio` field is the single
 * source of framing (a prompt that names one would pin it against the dropdown —
 * factory-presets.test.ts), so the words come out and the field carries it.
 */
const RATIO_CLAUSE = /,\s*\d{1,2}:\d{1,2}(?:\s+(?:vertical|portrait|square|tall|ultra-wide|landscape))?(?=[,.])/

export const slugOf = (label: string): string =>
  label
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")

/**
 * The tile's prompt as a preset prompt: each slot phrase (the headline the picture
 * shows, line by line) becomes `"{TEXT || <that phrase>}"`, `"{TEXT2 || …}"`, …, so an
 * unedited run reproduces the tile and a filled one carries the person's words.
 * Nothing else changes.
 */
export function templatePrompt(t: LedgerTemplate): string {
  if (t.textDefault !== undefined) {
    if (!/\{TEXT\}/.test(t.prompt)) throw new Error(`${t.id}: textDefault given but the prompt has no {TEXT}`)
    if (/[{}]/.test(t.prompt.replace(/\{TEXT\}/g, ""))) throw new Error(`${t.id}: a brace besides {TEXT} would read as a placeholder`)
    let prompt = t.prompt.replace(/\{TEXT\}/g, `{${TEXT_SLOT} || ${t.textDefault}}`)
    if (t.figureHeadline) prompt = `${prompt} ${FIGURE_NOTE}`
    return prompt
  }
  if (/[{}]/.test(t.prompt)) throw new Error(`${t.id}: a brace in the prompt would read as a placeholder; say it in words`)
  let prompt = t.prompt.replace(RATIO_CLAUSE, "")
  slotPhrases(t).forEach((phrase, at) => {
    prompt = prompt.replace(new RegExp(`[“"]${escapeRegExp(phrase)}[”"]`), `"{${slotLabel(at + 1)} || ${phrase}}"`)
  })
  if (t.figureHeadline) prompt = `${prompt} ${FIGURE_NOTE}`
  return prompt
}

const escapeRegExp = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")

/** A ledger template as the factory catalog carries it (plain data; the type lives in packages/prompts). */
export function toPreset(ledger: TileLedger, t: LedgerTemplate): Record<string, unknown> {
  const data: Record<string, unknown> = {
    provider: t.model ?? ledger.model,
    resolution: ledger.resolution,
    aspectRatio: t.aspectRatio,
    prompt: templatePrompt(t),
  }
  if (t.negativePrompt) data.negativePrompt = t.negativePrompt
  const preset: Record<string, unknown> = { id: `generate-image/${t.id}`, name: t.name }
  if (t.who) preset.description = t.who
  preset.group = t.group
  if (t.section) preset.section = t.section
  if (t.platforms && t.platforms.length > 0) preset.platforms = t.platforms
  if (t.minReferences) preset.minReferences = t.minReferences
  preset.data = data
  return preset
}

const HEADER = (group: string) =>
  `// GENERATED by tools/preset-tiles/build.mts from tools/preset-tiles/ledger.json — do not edit.
// Create Image tiles, tab "${group}": each preset's prompt is the one that rendered its picture.
import type { FactoryPreset } from "../types.js"

`

const constName = (group: string) => `TILES_${slugOf(group).toUpperCase().replace(/-/g, "_")}`

function literal(value: unknown, indent: string): string {
  if (Array.isArray(value)) return `[${value.map((v) => JSON.stringify(v)).join(", ")}]`
  if (value && typeof value === "object") {
    const inner = indent + "  "
    const rows = Object.entries(value as Record<string, unknown>).map(([k, v]) => `${inner}${k}: ${literal(v, inner)},`)
    return `{\n${rows.join("\n")}\n${indent}}`
  }
  return JSON.stringify(value)
}

/** The group tabs in ledger order (first appearance). */
export function groupsOf(ledger: TileLedger): readonly string[] {
  return [...new Set(ledger.templates.map((t) => t.group))]
}

/** File path (relative to the repo root) → source, for every module the build writes: the preset modules and the app's preset copy per language. */
export function renderModules(ledger: TileLedger): Record<string, string> {
  const out: Record<string, string> = {}
  const groups = groupsOf(ledger)
  for (const group of groups) {
    const rows = ledger.templates.filter((t) => t.group === group).map((t) => `  ${literal(toPreset(ledger, t), "  ")},`)
    out[`${TILES_DIR_PATH}/${slugOf(group)}.generated.ts`] = `${HEADER(group)}export const ${constName(group)}: readonly FactoryPreset[] = [\n${rows.join("\n")}\n]\n`
  }
  for (const locale of COPY_LOCALES) out[copyModulePath(locale)] = renderCopyModule(ledger, locale)
  const imports = groups.map((g) => `import { ${constName(g)} } from "./${slugOf(g)}.generated.js"`).join("\n")
  const spread = groups.map((g) => `  ...${constName(g)},`).join("\n")
  out[`${TILES_DIR_PATH}/index.generated.ts`] = `// GENERATED by tools/preset-tiles/build.mts from tools/preset-tiles/ledger.json — do not edit.
// Every Create Image tile preset, tab by tab, in ledger order.
import type { FactoryPreset } from "../types.js"
${imports}

export const GENERATE_IMAGE_TILE_PRESETS: readonly FactoryPreset[] = [
${spread}
]
`
  return out
}
