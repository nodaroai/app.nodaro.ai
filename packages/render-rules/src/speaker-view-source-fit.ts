/**
 * What the shape of a source video means for a Speaker View render, as pure
 * rules the route and both engines call (the editor's badge too):
 *
 *  - the canvas a render is drawn at (SV7: fixed per aspect and quality) and
 *    the two upscale lines (the whole-clip source warning and the region
 *    editor's drawn-box chip);
 *  - D18 (decided 2026-10-11): a source already at or narrower than the target
 *    aspect has no extra width to follow a speaker across, so it is refused
 *    BEFORE any charge;
 *  - D10 (decided 2026-10-11): a low-resolution source still renders at the
 *    fixed canvas, with a warning that names the upscale. Never a refusal. The
 *    warning line is 2.5x (decided 2026-10-12) and it always judges the FINAL
 *    canvas, whatever quality is being rendered (decided 2026-10-12), so it
 *    shows from the Preview on.
 *
 * The canvas sizes are the cloud plugin's (`canvas.ts`); the app mirrors them
 * here ONCE and the region editor reads this copy. `plugin-geometry-cases.json`
 * (generated by the plugin, pinned by `region-geometry-plugin-parity.test.ts`)
 * holds them to what it draws.
 */
import { isEdlTargetAspect, type EdlTargetAspect } from "@nodaro/shared/edl"

export interface SpeakerViewSize { readonly width: number; readonly height: number }

/**
 * Above this upscale the WHOLE-CLIP source gets the "will look soft" warning
 * (D10). Decided 2026-10-12: 2.5x, so 1080p and 1440p sources into 9:16 are
 * quiet (1.8x, 1.3x) and 720p and below warn (2.7x+).
 *
 * TWO thresholds, on purpose (decided 2026-10-12): this one judges the floor
 * of the whole frame, where 1.8x on a 1080p phone-shaped crop is ordinary. A
 * region the person DREW is a tighter crop of the picture, so its chip keeps
 * the stricter `SPEAKER_VIEW_BOX_UPSCALE_WARN`.
 */
export const SPEAKER_VIEW_SOURCE_UPSCALE_WARN = 2.5

/**
 * Above this upscale a drawn box's chip in the region editor turns amber
 * (SV8 a), as before: 1.5x. A separate constant from the source warning; the
 * two lines answer different questions and must not be merged back into one.
 */
export const SPEAKER_VIEW_BOX_UPSCALE_WARN = 1.5

const FINAL: Readonly<Record<EdlTargetAspect, SpeakerViewSize>> = {
  "16:9": { width: 1920, height: 1080 },
  "9:16": { width: 1080, height: 1920 },
  "1:1": { width: 1080, height: 1080 },
  "4:5": { width: 1080, height: 1350 },
}
const PREVIEW: Readonly<Record<EdlTargetAspect, SpeakerViewSize>> = {
  "16:9": { width: 1280, height: 720 },
  "9:16": { width: 720, height: 1280 },
  "1:1": { width: 720, height: 720 },
  "4:5": { width: 720, height: 900 },
}

/** The canvas a render of this aspect and quality is drawn at (SV7 a). */
export function speakerViewCanvas(aspect: EdlTargetAspect, quality: "proxy" | "final" = "final"): SpeakerViewSize {
  return { ...(quality === "proxy" ? PREVIEW : FINAL)[aspect] }
}

/** How close to the target's shape counts as "at" it: 1 %. A 1080×1918 file is
 *  9:16 rounded to even pixels, not a picture with width to spare. */
const AT_ASPECT_TOLERANCE_PERCENT = 1

const RATIO: Readonly<Record<EdlTargetAspect, readonly [number, number]>> = {
  "16:9": [16, 9],
  "9:16": [9, 16],
  "1:1": [1, 1],
  "4:5": [4, 5],
}

const known = (s: SpeakerViewSize | undefined): s is SpeakerViewSize =>
  !!s && Number.isFinite(s.width) && Number.isFinite(s.height) && s.width > 0 && s.height > 0

export interface SpeakerViewSourceRefusal {
  readonly code: "source-not-wider"
  readonly message: string
}

/** Widest to narrowest, the order the alternatives are offered in. */
const WIDE_TO_NARROW: readonly EdlTargetAspect[] = ["16:9", "1:1", "4:5", "9:16"]

/** True when the source is wider than the target by more than rounding. */
function widerThan(source: SpeakerViewSize, targetAspect: EdlTargetAspect): boolean {
  const [tw, th] = RATIO[targetAspect]
  // source.width / source.height > (tw / th) * (1 + tolerance)
  return source.width * th * 100 > tw * source.height * (100 + AT_ASPECT_TOLERANCE_PERCENT)
}

const listOf = (items: readonly string[]): string =>
  items.length <= 1 ? items.join("") : `${items.slice(0, -1).join(", ")} or ${items[items.length - 1]}`

/**
 * D18. Null when the source is wider than the target by more than rounding, or
 * when its size or the aspect is unknown (a rule cannot refuse what it cannot
 * measure; the caller that probed the clip decides what an unknown size
 * means). Compared by cross-multiplication, never by float equality.
 *
 * The way out the message offers is only ever one that exists: the targets
 * THIS picture is wider than, or just a wider video when there are none (a
 * phone clip refused for 9:16 has no narrower aspect to switch to).
 */
export function speakerViewSourceAspectRefusal(source: SpeakerViewSize, targetAspect: EdlTargetAspect): SpeakerViewSourceRefusal | null {
  if (!known(source) || !isEdlTargetAspect(targetAspect)) return null
  if (widerThan(source, targetAspect)) return null
  const alternatives = WIDE_TO_NARROW.filter((a) => a !== targetAspect && widerThan(source, a))
  return {
    code: "source-not-wider",
    message:
      `This video is ${source.width}×${source.height}, already as narrow as ${targetAspect} or narrower, so there is no extra width to follow a speaker across. ` +
      (alternatives.length > 0 ? `Use a wider video, or choose ${listOf(alternatives)}.` : "Use a wider video."),
  }
}

export interface SpeakerViewSourceUpscale {
  /** The cover crop of the whole frame, in source pixels (whole pixels, rounded down). */
  readonly crop: SpeakerViewSize
  /** The canvas it is enlarged to. */
  readonly canvas: SpeakerViewSize
  /** Canvas width over crop width (1 = none). */
  readonly factor: number
  /** True above `SPEAKER_VIEW_SOURCE_UPSCALE_WARN`. */
  readonly warn: boolean
  /** The sentence naming the upscale; present only when `warn`. */
  readonly message?: string
}

/**
 * D10. The enlargement a low-resolution source gets when the whole frame is
 * cover-cropped to the target. A tighter region (a framed face) enlarges
 * MORE, so this is the floor, not the worst case. Undefined when the size or
 * the aspect is unknown.
 *
 * Always measured against the FINAL canvas (decided 2026-10-12): there is no
 * quality argument, so a Preview warns exactly as the final render would. The
 * Preview is where a person decides whether to spend on the final.
 */
export function speakerViewSourceUpscale(
  source: SpeakerViewSize,
  targetAspect: EdlTargetAspect,
): SpeakerViewSourceUpscale | undefined {
  if (!known(source) || !isEdlTargetAspect(targetAspect)) return undefined
  const [tw, th] = RATIO[targetAspect]
  const cropW = Math.min(source.width, (source.height * tw) / th)
  const cropH = Math.min(source.height, (source.width * th) / tw)
  const canvas = speakerViewCanvas(targetAspect, "final")
  const factor = canvas.width / cropW
  const crop = { width: Math.floor(cropW), height: Math.floor(cropH) }
  const warn = factor > SPEAKER_VIEW_SOURCE_UPSCALE_WARN
  return {
    crop,
    canvas,
    factor,
    warn,
    ...(warn
      ? {
          message:
            `This video is ${source.width}×${source.height}. A ${targetAspect} picture is cut from it at ${crop.width}×${crop.height} and enlarged ${factor.toFixed(1)}× to ${canvas.width}×${canvas.height}, so it will look soft.`,
        }
      : {}),
  }
}
