#!/usr/bin/env node
// Regenerates the editor's node-docs maps from the docs site's snapshot.
//
//   npm -w frontend run gen:node-docs                  # from the committed snapshot
//   npm -w frontend run gen:node-docs -- --live        # fetch the live map first
//   npm -w frontend run gen:node-docs -- <file|url>    # replace the snapshot first
//
// The snapshot (frontend/src/lib/node-docs/node-docs-links.json) is the docs
// site's list of node pages. The docs site rebuilds it on every deploy and
// serves it at LIVE_URL. The app never ships it: it ships two maps built
// from it here. `node-docs-map.generated.ts` holds which sections each page has
// (a deep link is shown only to a section the page has). The summaries go in
// `node-docs-summaries.generated.ts`, a separate chunk that is loaded only when
// the docs popover opens in English, the one language the summaries exist in.
// `lib/node-docs/__tests__/node-docs.test.ts` fails when these files and the
// snapshot disagree.

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const DIR = resolve(dirname(fileURLToPath(import.meta.url)), "../frontend/src/lib/node-docs")
const SNAPSHOT = resolve(DIR, "node-docs-links.json")
const LIVE_URL = "https://nodaro.ai/docs/node-links.json"
const HEADER = "// GENERATED by scripts/gen-node-docs.mjs from node-docs-links.json. Do not edit.\n"

/** The replacement snapshot's text, or null to keep the committed one. */
async function incomingText(arg) {
  if (!arg) return null
  const url = arg === "--live" ? LIVE_URL : /^https?:\/\//.test(arg) ? arg : null
  if (!url) {
    // npm runs the script from frontend/; INIT_CWD is where it was typed.
    return readFileSync(resolve(process.env.INIT_CWD ?? process.cwd(), arg), "utf-8")
  }
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
  return res.text()
}

const text = await incomingText(process.argv[2])
if (text !== null) {
  const parsed = JSON.parse(text)
  if (parsed.version !== 1 || !Array.isArray(parsed.nodes) || typeof parsed.sections !== "object") {
    throw new Error("not a node-links snapshot (version 1, nodes[], sections{})")
  }
  // One stable format (the site serves it minified), so a refresh diffs to what changed.
  writeFileSync(SNAPSHOT, `${JSON.stringify(parsed, null, 2)}\n`)
}

const snapshot = JSON.parse(readFileSync(SNAPSHOT, "utf-8"))
const known = new Set(Object.keys(snapshot.sections))
const quote = (s) => JSON.stringify(s)

for (const node of snapshot.nodes) {
  const unknown = node.sections.filter((s) => !known.has(s))
  if (unknown.length > 0) throw new Error(`${node.type}: unknown section ids ${unknown.join(", ")}`)
}

const sections = snapshot.nodes.map((n) => `  ${quote(n.type)}: [${n.sections.map(quote).join(", ")}],`).join("\n")
const aliases = Object.entries(snapshot.aliases ?? {}).map(([from, to]) => `  ${quote(from)}: ${quote(to)},`).join("\n")
writeFileSync(
  resolve(DIR, "node-docs-map.generated.ts"),
  `${HEADER}import type { NodeDocsSection } from "./node-docs"

/** The date the docs site produced the snapshot. */
export const NODE_DOCS_SNAPSHOT_DATE = ${quote(snapshot.generatedAt)}

/** The sections each node's page has, in page order. */
export const NODE_DOCS_SECTIONS: Readonly<Record<string, readonly NodeDocsSection[]>> = {
${sections}
}

/** Types documented on another node's page. */
export const NODE_DOCS_ALIASES: Readonly<Record<string, string>> = {
${aliases}
}
`,
)

const summaries = snapshot.nodes.map((n) => `  ${quote(n.type)}: ${quote(n.summary)},`).join("\n")
writeFileSync(
  resolve(DIR, "node-docs-summaries.generated.ts"),
  `${HEADER}
/** Each node page's one-line description, in English. */
export const NODE_DOCS_SUMMARIES: Readonly<Record<string, string>> = {
${summaries}
}
`,
)

console.log(`node-docs: ${snapshot.nodes.length} pages, snapshot of ${snapshot.generatedAt}`)
